with
    MAIN as (
        select
            T2.COMPANY_ID,
            T1.CARDUP_PAYMENT_PAYMENT_TYPE,
            T2.CLUSTER_KMEANS,
            COUNT(DWH_CARDUP_PAYMENT_ID) COUNT_TX,
            SUM(CARDUP_PAYMENT_USD_AMT) SUM_TX
        from
            ADM.TRANSACTION.CARDUP_PAYMENT_DENORM_T T1
            join DEV.SBOX_SHILTON.TEST_CLUSTERING_RESULTS T2 on T1.CARDUP_PAYMENT_CUSTOMER_COMPANY_ID = T2.COMPANY_ID
        where
            true
            -- and CLUSTER_KMEANS = 2
            and DATE(CARDUP_PAYMENT_SUCCESS_AT_UTC_TS) >= DATE('2023-09-01')
            and DATE(CARDUP_PAYMENT_SUCCESS_AT_UTC_TS) <= DATE('2024-08-31')
            and CARDUP_PAYMENT_PAYMENT_TYPE = 'GST'
        group by
            1,
            2,
            3
    )
select
    COMPANY_ID,
    CLUSTER_KMEANS,
    APPROX_PERCENTILE(SUM_TX, 0.5),
    APPROX_PERCENTILE(COUNT_TX, 0.5)
from
    MAIN
group by
    1,
    2;

