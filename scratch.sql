    join DEV.SBOX_SHILTON.TEST_CLUSTERING_RESULTS T2 on T1.CARDUP_PAYMENT_CUSTOMER_COMPANY_ID = T2.COMPANY_ID
    left outer join RECENCY T3 on T3.COMPANY_ID = T1.CARDUP_PAYMENT_CUSTOMER_COMPANY_ID
