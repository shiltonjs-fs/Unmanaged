    -- TO_CHAR(DATE_TRUNC(month, DATE(CARDUP_PAYMENT_SUCCESS_AT_UTC_TS)), 'MON-YYYY'),
    CLUSTER_KMEANS,
    CARDUP_PAYMENT_PAYMENT_TYPE,
    COUNT(distinct CARDUP_PAYMENT_CUSTOMER_COMPANY_ID),
    COUNT(distinct DWH_CARDUP_PAYMENT_ID),
    SUM(CARDUP_PAYMENT_USD_AMT)
from
